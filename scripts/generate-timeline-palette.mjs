// npm install --prefix .tools/leonardo @adobe/leonardo-contrast-colors@1.1.0 --ignore-scripts
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Theme, Color} from '../.tools/leonardo/node_modules/@adobe/leonardo-contrast-colors/index.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const seeds = [
  ['pink', '樱粉', '#E94383', '#FCE5EE'], ['cyan', '湖青', '#00A7B5', '#D8F1E5'],
  ['violet', '藤紫', '#8B5CF6', '#EAE6FC'], ['gold', '麦金', '#D79B16', '#F7EFD9'],
  ['coral', '珊橙', '#EF783E', '#FAEEE3'], ['blue', '晴蓝', '#3B91E1', '#E1EFFF'],
  ['green', '豆绿', '#49A573', '#E9F3DF'], ['rose', '莓紫', '#BE55AE', '#EFE2F4'],
];
const lightRatios = {container: 1.2, content: 9, secondary: 6.4, accent: 3.2};
const darkRatios = {container: 1.8, content: 13, secondary: 9.6, accent: 4.8};
function generate(backgroundColor, ratios) {
  const colors = seeds.map(([id, , seed, pastel]) => new Color({
    name: id, colorKeys: [pastel, seed], colorSpace: 'CAM02', ratios,
  }));
  const theme = new Theme({colors, backgroundColor, output: 'HEX'});
  return theme.contrastColors.filter(c => c.name).map(c => Object.fromEntries(c.values.map(v => [v.name, v.value])));
}
function luminance(hex) {
  const rgb = hex.match(/[\da-f]{2}/gi).map(v => parseInt(v, 16) / 255)
    .map(v => v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4);
  return rgb[0] * .2126 + rgb[1] * .7152 + rgb[2] * .0722;
}
function ratio(a, b) {
  const x = luminance(a), y = luminance(b);
  return (Math.max(x, y) + .05) / (Math.min(x, y) + .05);
}
const light = generate('#FFFFFF', lightRatios);
const dark = generate('#10121A', darkRatios);
const presets = seeds.map(([id, name, seed, pastelAnchor], i) => ({id, name, seed, pastelAnchor, light: light[i], dark: dark[i]}));
for (const p of presets) for (const mode of ['light', 'dark']) {
  const t = p[mode];
  const title = ratio(t.content, t.container), secondary = ratio(t.secondary, t.container);
  if (title < 7 || secondary < 4.5) throw new Error(`${p.id}/${mode}: title=${title}, secondary=${secondary}`);
  t.contrast = {title: +title.toFixed(3), secondary: +secondary.toFixed(3)};
}
const tokens = {
  generator: '@adobe/leonardo-contrast-colors@1.1.0',
  reference: 'https://github.com/adobe/leonardo/tree/main/packages/contrast-colors',
  colorspace: 'CAM02', background: {light: '#FFFFFF', dark: '#10121A'},
  targets: {light: lightRatios, dark: darkRatios}, presets,
};
fs.mkdirSync(path.join(root, 'design'), {recursive: true});
fs.writeFileSync(path.join(root, 'design/timeline-palette.json'), JSON.stringify(tokens, null, 2) + '\n');
const argb = hex => `0xFF${hex.slice(1).toUpperCase()}`;
const rows = presets.map(p => `    TimelinePreset("${p.id}", "${p.name}", ${[
  p.light.container, p.light.content, p.light.secondary, p.light.accent,
  p.dark.container, p.dark.content, p.dark.secondary, p.dark.accent,
].map(argb).join(', ')}),`).join('\n');
fs.writeFileSync(path.join(root, 'app/src/main/java/com/timeagent/ui/TimelinePaletteTokens.kt'),
  `// Generated by scripts/generate-timeline-palette.mjs using Leonardo 1.1.0.\n` +
  `// Target contrast and input hues: design/timeline-palette.json.\n` +
  `package com.timeagent.ui\n\ninternal val GeneratedTimelinePresets = listOf(\n${rows}\n)\n`);
